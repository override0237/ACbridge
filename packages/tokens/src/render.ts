/** Pure generators: tokens -> CSS text and RN theme text. (build.ts writes them; tests import them.) */
import { colors, layout, motion, radius, shadow, space, target, type, type ColorSet } from './tokens';

const kebab = (s: string): string => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const colorVars = (set: ColorSet, indent: string): string =>
  (Object.entries(set) as [string, string][]).map(([k, v]) => `${indent}--acb-color-${kebab(k)}: ${v};`).join('\n');

export function renderCss(): string {
  const scale = Object.entries(space).map(([k, v]) => `  --acb-space-${k}: ${v}px;`).join('\n');
  return `/* GENERATED by packages/tokens/src/build.ts from tokens.ts. Do not edit by hand. */
:root {
  color-scheme: light dark;
${colorVars(colors.light, '  ')}
${scale}
  --acb-radius-card: ${radius.card}px;
  --acb-radius-button: ${radius.button}px;
  --acb-radius-pill: ${radius.pill}px;
  --acb-shadow-raised: ${shadow.raised};
  --acb-font-family: ${type.fontFamily};
  --acb-font-size-body: ${type.size.body}px;
  --acb-font-size-instruction: ${type.size.instruction}px;
  --acb-font-size-small: ${type.size.small}px;
  --acb-font-size-heading: ${type.size.heading}px;
  --acb-font-size-display: ${type.size.display}px;
  --acb-line-height: ${type.lineHeight};
  --acb-target-min: ${target.min}px;
  --acb-motion-fast: ${motion.fast}ms;
  --acb-motion-base: ${motion.base}ms;
  --acb-motion-slow: ${motion.slow}ms;
  --acb-max-content-width: ${layout.maxContentWidth}px;
}

/* Follow the system setting, unless the user chose light in Settings. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${colorVars(colors.dark, '    ')}
  }
}

/* Manual override from Settings. */
:root[data-theme='dark'] {
${colorVars(colors.dark, '  ')}
}

/* Scoped themes: show light and dark side by side (style guide) or force a region to one mode.
   .acb-vars-light only pins the light VARIABLES (no background), for screens that are still light-only. */
.acb-vars-light,
.acb-theme-light {
${colorVars(colors.light, '  ')}
}
.acb-theme-light {
  background: var(--acb-color-surface);
  color: var(--acb-color-text);
}
.acb-theme-dark {
${colorVars(colors.dark, '  ')}
  background: var(--acb-color-surface);
  color: var(--acb-color-text);
}

/* Reduced motion: no animation at all. */
@media (prefers-reduced-motion: reduce) {
  :root {
    --acb-motion-fast: 0ms;
    --acb-motion-base: 0ms;
    --acb-motion-slow: 0ms;
  }
}
`;
}

export function renderTheme(): string {
  const theme = {
    colors,
    space,
    radius,
    type: { fontFamily: 'System', size: type.size, lineHeight: type.lineHeight, weight: type.weight },
    target,
    motion,
  };
  return `// GENERATED by packages/tokens/src/build.ts from tokens.ts. Do not edit by hand.
// React Native theme: the same values as the web CSS variables (shadows are platform specific and live in the components).
export const theme = ${JSON.stringify(theme, null, 2)} as const;

export type Theme = typeof theme;
export type ThemeMode = keyof typeof theme.colors;
`;
}
