// Extracts the geometry from the designer's SVG (logo/acbridge_logo.svg) into src/paths.ts, so the code never contains a hand-copied path.
//   node packages/brand/scripts/extract-paths.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const svg = readFileSync(join(here, '..', '..', '..', 'logo', 'acbridge_logo.svg'), 'utf8');

const letters = [...svg.matchAll(/<path d="([^"]+)" fill="#[0-9A-Fa-f]{6}"\/>/g)].map((m) => m[1]);
if (letters.length !== 2) throw new Error(`expected 2 lettering paths, found ${letters.length}`);
const group = /<g transform="translate\(([\d.]+),([\d.]+)\)"[^>]*>([\s\S]*?)<\/g>/.exec(svg);
if (!group) throw new Error('glyph group not found');
const arch = /<path d="(M 36 80 Q 66 16 96 80)" stroke="url\(#gold\)" stroke-width="(\d+)"/.exec(group[3]);
const baseline = /<path d="(M 0 80 L 96 80)" stroke="url\(#gold\)" stroke-width="(\d+)"/.exec(group[3]);
const post = /<path d="(M 6 80 L 26 12)" stroke="url\(#gold\)" stroke-width="(\d+)"/.exec(group[3]);
const dots = [...group[3].matchAll(/<circle cx="(\d+)" cy="(\d+)" r="(\d+)"/g)].map((m) => ({ cx: +m[1], cy: +m[2], r: +m[3] }));
if (!arch || !baseline || !post || dots.length !== 2) throw new Error('glyph parts not found');
const view = /viewBox="([\d. ]+)"/.exec(svg)[1];

const out = `// GENERATED by packages/brand/scripts/extract-paths.mjs from logo/acbridge_logo.svg. Do not edit by hand.
// The geometry of the designer's logo, unchanged. Colours are NOT here: they come from @acbridge/tokens.

/** Full logo viewBox: "AC" + glyph + "bridge". */
export const LOGO_VIEWBOX = ${JSON.stringify(view)};
export const LOGO_WIDTH = ${view.split(' ')[2]};
export const LOGO_HEIGHT = ${view.split(' ')[3]};

/** The letters "AC" and "bridge" as filled outlines. */
export const LETTERS_AC = ${JSON.stringify(letters[0])};
export const LETTERS_BRIDGE = ${JSON.stringify(letters[1])};

/** The gold glyph (a leaning post, an arch span and a baseline) is drawn in its own 0..96 box and placed at this translation. */
export const GLYPH_TRANSLATE = { x: ${group[1]}, y: ${group[2]} } as const;
export const GLYPH = {
  arch: { d: ${JSON.stringify(arch[1])}, strokeWidth: ${arch[2]} },
  baseline: { d: ${JSON.stringify(baseline[1])}, strokeWidth: ${baseline[2]} },
  post: { d: ${JSON.stringify(post[1])}, strokeWidth: ${post[2]} },
  /** Round ends: the foot of the post and its tip. */
  dots: ${JSON.stringify(dots)} as { cx: number; cy: number; r: number }[],
  /** Gradient axis in glyph coordinates (userSpaceOnUse), light gold at the top-left to deep gold at the bottom-right. */
  gradient: { x1: 0, y1: 0, x2: 96, y2: 84 },
} as const;

/** Tight viewBox around the glyph alone (for the mark, favicons and app icons). */
export const MARK_VIEWBOX = '-8 2 116 88';
`;
writeFileSync(join(here, '..', 'src', 'paths.ts'), out);
console.log('wrote packages/brand/src/paths.ts');
